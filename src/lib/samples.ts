function normalizeKeyword(s: string): string {
  return s.trim().toLowerCase().replace(/\s+/g, " ");
}

function simpleHash(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) >>> 0;
  }
  return h;
}

